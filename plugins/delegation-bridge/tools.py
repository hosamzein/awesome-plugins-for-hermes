"""
Delegation Bridge Tools for Hermes Agent
Implements Review-First cross-agent delegation across Cursor, Codex, Antigravity, OpenCode, and Kimi.
"""

import os
import subprocess
import sys
from typing import Dict, Any, Optional, List

# Ensure scripts dir is accessible
scripts_dir = os.path.join(os.path.dirname(__file__), "scripts")
if scripts_dir not in sys.path:
    sys.path.insert(0, scripts_dir)

try:
    from .scripts.relay import run_relay, AGENTS
except ImportError:
    try:
        from scripts.relay import run_relay, AGENTS
    except ImportError:
        from relay import run_relay, AGENTS

def delegate_task(
    agent: str,
    brief: str,
    cd: str = ".",
    model: Optional[str] = None,
    read_only: bool = False,
    session: Optional[str] = None
) -> Dict[str, Any]:
    """
    Dispatch self-contained task instructions to an implementer CLI agent.
    
    Args:
        agent: Target agent ('cursor', 'codex', 'antigravity', 'opencode', 'kimi').
        brief: Comprehensive, self-contained instructions.
        cd: Target workspace directory.
        model: Optional model override.
        read_only: Run in diagnostic/read-only mode if True.
        session: Optional session ID to resume.
    """
    return run_relay(
        agent=agent,
        brief=brief,
        cd=cd,
        model=model,
        read_only=read_only,
        session=session
    )

def review_task(run_id: Optional[str] = None, workspace: str = ".") -> Dict[str, Any]:
    """Inspect output status and git diff generated by delegated agent."""
    try:
        diff = subprocess.run(["git", "diff"], cwd=workspace, capture_output=True, text=True, timeout=15).stdout.strip()
        stat = subprocess.run(["git", "diff", "--stat"], cwd=workspace, capture_output=True, text=True, timeout=15).stdout.strip()
        status = subprocess.run(["git", "status", "-s"], cwd=workspace, capture_output=True, text=True, timeout=15).stdout.strip()
        return {
            "run_id": run_id,
            "has_changes": bool(diff or status),
            "summary_stat": stat,
            "status": status,
            "full_diff": diff
        }
    except Exception as e:
        return {"error": str(e)}

def land_task(workspace: str = ".", commit_message: str = "chore: land delegated task") -> Dict[str, Any]:
    """Approve and commit code changes made by implementer."""
    try:
        subprocess.run(["git", "add", "."], cwd=workspace, check=True)
        res = subprocess.run(["git", "commit", "-m", commit_message], cwd=workspace, capture_output=True, text=True, check=True)
        return {
            "landed": True,
            "output": res.stdout.strip()
        }
    except Exception as e:
        return {"landed": False, "error": str(e)}

def reject_task(workspace: str = ".") -> Dict[str, Any]:
    """Discard uncommitted modifications and restore working tree cleanly."""
    try:
        subprocess.run(["git", "restore", "."], cwd=workspace, check=True)
        subprocess.run(["git", "clean", "-fd"], cwd=workspace, check=True)
        return {"rejected": True, "message": "Working tree restored clean."}
    except Exception as e:
        return {"rejected": False, "error": str(e)}

def list_supported_implementers() -> List[str]:
    """List all supported implementer agents."""
    return list(AGENTS.keys())
